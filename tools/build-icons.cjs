// Renders react-icons to a static SVG sprite (site/assets/icons.svg).
// The site itself never loads React; this runs once, on your machine.
//
//   node tools/build-icons.cjs [path/to/node_modules-with-react-icons]
//
// Defaults to the old portfolio's node_modules. To add an icon: add a line to
// ICONS below, rerun, then use <svg class="i"><use href="/assets/icons.svg#id"/></svg>.
const path = require('path');
const fs = require('fs');
const { createRequire } = require('module');

const modules = path.resolve(process.argv[2] || path.join(process.env.HOME, 'Desktop/portfolio/node_modules'));
const req = createRequire(path.join(modules, 'noop.js'));
const { createElement } = req('react');
const { renderToStaticMarkup } = req('react-dom/server');

// sprite id: [react-icons set, component name]
const ICONS = {
  python: ['si', 'SiPython'],
  fastapi: ['si', 'SiFastapi'],
  flask: ['si', 'SiFlask'],
  scrapy: ['si', 'SiScrapy'],
  selenium: ['si', 'SiSelenium'],
  opencv: ['si', 'SiOpencv'],
  tensorflow: ['si', 'SiTensorflow'],
  mysql: ['si', 'SiMysql'],
  postgresql: ['si', 'SiPostgresql'],
  sqlalchemy: ['si', 'SiSqlalchemy'],
  docker: ['si', 'SiDocker'],
  jenkins: ['si', 'SiJenkins'],
  s3: ['si', 'SiAmazons3'],
  linux: ['si', 'SiLinux'],
  fedora: ['si', 'SiFedora'],
  git: ['si', 'SiGit'],
  bash: ['si', 'SiGnubash'],
  cmake: ['si', 'SiCmake'],
  cplusplus: ['si', 'SiCplusplus'],
  javascript: ['si', 'SiJavascript'],
  chromium: ['si', 'SiGooglechrome'],
  qt: ['si', 'SiQt'],
  kde: ['si', 'SiKde'],
  emacs: ['si', 'SiGnuemacs'],
  github: ['si', 'SiGithub'],
  linkedin: ['fa', 'FaLinkedin'],
  terminal: ['go', 'GoTerminal'],
  star: ['go', 'GoStarFill'],
  merge: ['go', 'GoGitMerge'],
  mail: ['fi', 'FiMail'],
  'chevron-left': ['fi', 'FiChevronLeft'],
  'chevron-right': ['fi', 'FiChevronRight'],
  'chevron-down': ['fi', 'FiChevronDown'],
  copy: ['fi', 'FiCopy'],
  briefcase: ['fi', 'FiBriefcase'],
  'arrow-right': ['fi', 'FiArrowRight'],
  download: ['fi', 'FiDownload'],
  folder: ['fi', 'FiFolder'],
  pen: ['fi', 'FiEdit3'],
  check: ['fi', 'FiCheck'],
  sun: ['fi', 'FiSun'],
  moon: ['fi', 'FiMoon'],
};

const symbols = Object.entries(ICONS).map(([id, [set, name]]) => {
  const Icon = req(`react-icons/${set}`)[name];
  if (!Icon) throw new Error(`react-icons/${set} has no ${name}`);
  const svg = renderToStaticMarkup(createElement(Icon));
  const viewBox = svg.match(/viewBox="([^"]+)"/)[1];
  // Feather (fi) icons are strokes; everything else is fill.
  const stroked = set === 'fi';
  const body = svg.replace(/^<svg[^>]*>/, '').replace(/<\/svg>$/, '');
  const paint = stroked
    ? 'fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round"'
    : 'fill="currentColor"';
  return `  <symbol id="${id}" viewBox="${viewBox}" ${paint}>${body}</symbol>`;
});

const out = path.join(__dirname, '../site/assets/icons.svg');
fs.writeFileSync(
  out,
  `<svg xmlns="http://www.w3.org/2000/svg">\n<!-- Generated by tools/build-icons.cjs from react-icons. Simple Icons (CC0), Font Awesome (CC BY 4.0), Octicons (MIT), Feather (MIT). -->\n${symbols.join('\n')}\n</svg>\n`,
);
console.log(`${symbols.length} icons -> ${path.relative(process.cwd(), out)}`);
